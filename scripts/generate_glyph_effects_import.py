#!/usr/bin/env python3
"""Parse staged Glyph workbook rows into base-stat and effect records.

Each equipment sheet is split into rarity sections. A section starts with an
"All glyphs" base-stat row (or, for SS, a row naming the SS glyph that also
carries its base stat; the SS effect is on the following row). The remaining
rows in a section are glyph effects with one value per tier column.

Values are kept verbatim. A numeric value is only added when the cell is a bare
number or an explicit percentage, because the workbook mixes fractions (0.05)
with percent strings (8.5%) and the meaning of a fraction is left to curators.

Usage: generate_glyph_effects_import.py OUTPUT.sql
"""

import hashlib
import json
import re
import sys
from pathlib import Path

from generate_workbook_provenance_import import read_workbook, sql_string

WORKBOOK_PATH = Path("/home/jakubkolinsky/Downloads/Archero Glyphs.xlsx")
EQUIPMENT_SHEETS = ["Weapon", "Armor", "Bracelet", "Locket", "Ring", "Book", "Spirit"]
# Normalized tier codes; the Weapon sheet spells Ancient Legendary as ALE.
TIER_ALIASES = {"ALE": "AL"}


def layout(sheet: str) -> dict[str, str]:
    if sheet == "Spirit":
        return {"rarity": "A", "marker": "B", "name": "B", "desc": "C"}
    return {"rarity": "A", "marker": "G", "name": "H", "desc": "I"}


def tier_values(cells: dict[str, str], tiers: list[tuple[str, str]]) -> list[dict]:
    values = []
    for column, header in tiers:
        raw = cells.get(column, "").strip()
        if not raw or raw == "-":
            continue
        rank, plus, step = header.partition("+")
        entry: dict = {"tier": TIER_ALIASES.get(rank, rank) + plus + step, "header": header, "raw": raw}
        if re.fullmatch(r"-?\d+(\.\d+)?", raw):
            entry["number"] = float(raw)
        elif re.fullmatch(r"-?\d+(\.\d+)?%", raw):
            entry["percent"] = float(raw[:-1])
        values.append(entry)
    return values


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Usage: generate_glyph_effects_import.py OUTPUT.sql")

    sheets = dict(read_workbook(WORKBOOK_PATH))
    fingerprint = hashlib.sha256(WORKBOOK_PATH.read_bytes()).hexdigest()
    base_stats: list[tuple] = []
    effects: list[tuple] = []

    for sheet in EQUIPMENT_SHEETS:
        cols = layout(sheet)
        rows = sheets[sheet]
        header = rows[0][1]
        tiers = [(column, label) for column, label in header.items()]
        section_index = 0
        rarity = ""
        pending_ss: tuple | None = None

        for row_number, cells in rows:
            if row_number <= 2:
                continue
            name = cells.get(cols["name"], "").strip()
            desc = cells.get(cols["desc"], "").strip()
            is_ss_header = name.startswith("SS Glyph")
            is_base = cells.get(cols["marker"], "").strip() == "All glyphs" or is_ss_header

            if pending_ss is not None:
                if name or not desc:
                    raise SystemExit(f"{sheet} row {row_number}: expected the SS effect row")
                ss_name, ss_row = pending_ss
                effects.append((sheet, ss_row, row_number, section_index, rarity, ss_name, desc, tier_values(cells, tiers)))
                pending_ss = None
                continue

            if is_base:
                section_index += 1
                rarity = cells.get(cols["rarity"], "").strip().upper()
                base_stats.append((sheet, row_number, section_index, rarity, desc, tier_values(cells, tiers)))
                if is_ss_header:
                    pending_ss = (name.split(":", 1)[1].strip(), row_number)
                continue

            if not name:
                raise SystemExit(f"{sheet} row {row_number}: effect row without a glyph name")
            effects.append((sheet, row_number, None, section_index, rarity, name, desc, tier_values(cells, tiers)))

    def row_key(sheet: str, row: int) -> str:
        return sql_string(f"workbook:Archero Glyphs.xlsx:sheet:{sheet}:row:{row}")

    base_values = ",\n".join(
        f"    ({row_key(s, r)}, {sql_string(s)}, {idx}, {sql_string(rar)}, {sql_string(stat)}, "
        f"{sql_string(json.dumps(vals, ensure_ascii=True))}::jsonb)"
        for s, r, idx, rar, stat, vals in base_stats
    )
    effect_values = ",\n".join(
        f"    ({row_key(s, r)}, {row_key(s, er) if er else 'null'}, {sql_string(s)}, {idx}, {sql_string(rar)}, "
        f"{sql_string(name)}, {sql_string(desc)}, {sql_string(json.dumps(vals, ensure_ascii=True))}::jsonb)"
        for s, r, er, idx, rar, name, desc, vals in effects
    )

    Path(sys.argv[1]).write_text(
        f"""-- Generated by scripts/generate_glyph_effects_import.py from Archero Glyphs.xlsx
-- sha256 {fingerprint}. {len(base_stats)} section base stats, {len(effects)} glyph effects.
-- Parsed from rows already staged in glyph_source_rows; everything stays unreviewed.
create table glyph_source_base_stats (
  id uuid primary key default gen_random_uuid(),
  glyph_source_row_id uuid not null unique references glyph_source_rows(id) on delete cascade,
  equipment_category text not null,
  section_index integer not null check (section_index > 0),
  section_rarity text not null,
  stat_name text not null,
  tier_values jsonb not null default '[]'::jsonb
);

create table glyph_source_effects (
  id uuid primary key default gen_random_uuid(),
  glyph_source_row_id uuid not null unique references glyph_source_rows(id) on delete cascade,
  effect_source_row_id uuid references glyph_source_rows(id) on delete cascade,
  equipment_category text not null,
  section_index integer not null check (section_index > 0),
  section_rarity text not null,
  glyph_name text not null,
  effect_description text not null,
  tier_values jsonb not null default '[]'::jsonb
);

alter table glyph_source_base_stats enable row level security;
alter table glyph_source_effects enable row level security;

create policy "Admins can manage glyph source base stats" on glyph_source_base_stats
for all to authenticated using (is_admin()) with check (is_admin());

create policy "Admins can manage glyph source effects" on glyph_source_effects
for all to authenticated using (is_admin()) with check (is_admin());

with staged as (
  select glyph_source_rows.id, source_records.external_key
  from glyph_source_rows
  join source_records on source_records.id = glyph_source_rows.source_record_id
  where source_records.entity_type = 'glyph_source_row'
),
parsed (external_key, equipment_category, section_index, section_rarity, stat_name, tier_values) as (
  values
{base_values}
)
insert into glyph_source_base_stats (
  glyph_source_row_id, equipment_category, section_index, section_rarity, stat_name, tier_values
)
select staged.id, parsed.equipment_category, parsed.section_index, parsed.section_rarity, parsed.stat_name, parsed.tier_values
from parsed
join staged on staged.external_key = parsed.external_key
on conflict (glyph_source_row_id) do update
set
  equipment_category = excluded.equipment_category,
  section_index = excluded.section_index,
  section_rarity = excluded.section_rarity,
  stat_name = excluded.stat_name,
  tier_values = excluded.tier_values;

with staged as (
  select glyph_source_rows.id, source_records.external_key
  from glyph_source_rows
  join source_records on source_records.id = glyph_source_rows.source_record_id
  where source_records.entity_type = 'glyph_source_row'
),
parsed (
  external_key, effect_external_key, equipment_category, section_index, section_rarity,
  glyph_name, effect_description, tier_values
) as (
  values
{effect_values}
)
insert into glyph_source_effects (
  glyph_source_row_id, effect_source_row_id, equipment_category, section_index, section_rarity,
  glyph_name, effect_description, tier_values
)
select
  staged.id,
  effect_row.id,
  parsed.equipment_category,
  parsed.section_index,
  parsed.section_rarity,
  parsed.glyph_name,
  parsed.effect_description,
  parsed.tier_values
from parsed
join staged on staged.external_key = parsed.external_key
left join staged effect_row on effect_row.external_key = parsed.effect_external_key
on conflict (glyph_source_row_id) do update
set
  effect_source_row_id = excluded.effect_source_row_id,
  equipment_category = excluded.equipment_category,
  section_index = excluded.section_index,
  section_rarity = excluded.section_rarity,
  glyph_name = excluded.glyph_name,
  effect_description = excluded.effect_description,
  tier_values = excluded.tier_values;
"""
    )
    print(f"{len(base_stats)} base stats, {len(effects)} effects")


if __name__ == "__main__":
    main()
